drop policy if exists "cajas_turno_select_gimnasio" on public.cajas_turno;
create policy "cajas_turno_select_gimnasio"
on public.cajas_turno
for select
to authenticated
using (
    exists (
        select 1
        from public.perfiles p
        where p.user_id = auth.uid()
          and lower(p.estado) = 'activo'
          and p.gimnasio_id = cajas_turno.gimnasio_id
          and (
              lower(p.rol) = 'administrador'
              or cajas_turno.usuario_id = auth.uid()
          )
    )
);

drop policy if exists "cajas_turno_insert_usuario" on public.cajas_turno;
create policy "cajas_turno_insert_usuario"
on public.cajas_turno
for insert
to authenticated
with check (
    usuario_id = auth.uid()
    and exists (
        select 1
        from public.perfiles p
        where p.user_id = auth.uid()
          and lower(p.estado) = 'activo'
          and p.gimnasio_id = cajas_turno.gimnasio_id
          and lower(p.rol) in ('administrador', 'recepcion')
    )
);

drop policy if exists "cajas_turno_update_usuario" on public.cajas_turno;
create policy "cajas_turno_update_usuario"
on public.cajas_turno
for update
to authenticated
using (
    exists (
        select 1
        from public.perfiles p
        where p.user_id = auth.uid()
          and lower(p.estado) = 'activo'
          and p.gimnasio_id = cajas_turno.gimnasio_id
          and lower(p.rol) in ('administrador', 'recepcion')
          and (lower(p.rol) = 'administrador' or cajas_turno.usuario_id = auth.uid())
