create table if not exists public.cajas_turno (
    id bigint generated by default as identity primary key,
    gimnasio_id uuid not null references public.gimnasios(id),
    usuario_id uuid not null references auth.users(id),
    usuario_nombre text not null,
    fecha date not null default current_date,
    hora_apertura time not null default localtime,
    hora_cierre time,
    monto_inicial numeric(12,2) not null default 0 check (monto_inicial >= 0),
    total_efectivo numeric(12,2) not null default 0,
    total_tarjeta numeric(12,2) not null default 0,
    total_generado numeric(12,2) not null default 0,
    monto_entregado numeric(12,2),
    diferencia numeric(12,2),
    estado text not null default 'abierta' check (estado in ('abierta', 'cerrada')),
    observaciones text,
    created_at timestamptz not null default now()
);

comment on table public.cajas_turno is 'Turnos de caja por usuario para asociar pagos, ventas POS, facturas e ingresos diarios.';
comment on column public.cajas_turno.monto_inicial is 'Efectivo inicial entregado al iniciar el turno.';
comment on column public.cajas_turno.total_efectivo is 'Total cobrado en efectivo durante el turno, sin incluir monto inicial.';
comment on column public.cajas_turno.total_tarjeta is 'Total cobrado por tarjeta/transferencia durante el turno.';
comment on column public.cajas_turno.diferencia is 'Monto entregado menos efectivo esperado: monto_inicial + total_efectivo.';

create unique index if not exists idx_cajas_turno_usuario_abierta
on public.cajas_turno (usuario_id)
where estado = 'abierta';

create index if not exists idx_cajas_turno_gimnasio_fecha
on public.cajas_turno (gimnasio_id, fecha desc);

create index if not exists idx_cajas_turno_gimnasio_estado
on public.cajas_turno (gimnasio_id, estado);

alter table public.pagos add column if not exists caja_turno_id bigint references public.cajas_turno(id);
alter table public.facturas add column if not exists caja_turno_id bigint references public.cajas_turno(id);
alter table public.ventas add column if not exists caja_turno_id bigint references public.cajas_turno(id);
alter table public.ingresos_diarios add column if not exists caja_turno_id bigint references public.cajas_turno(id);
alter table public.movimientos_inventario add column if not exists caja_turno_id bigint references public.cajas_turno(id);

create index if not exists idx_pagos_caja_turno on public.pagos (caja_turno_id);
create index if not exists idx_facturas_caja_turno on public.facturas (caja_turno_id);
create index if not exists idx_ventas_caja_turno on public.ventas (caja_turno_id);
create index if not exists idx_ingresos_diarios_caja_turno on public.ingresos_diarios (caja_turno_id);
create index if not exists idx_movimientos_inventario_caja_turno on public.movimientos_inventario (caja_turno_id);

create or replace function public.kilvio_current_user_profile()
returns table (
    gimnasio_id uuid,
    rol text,
    nombre text
)
language sql
stable
security invoker
set search_path = public
as $$
    select p.gimnasio_id, lower(p.rol), coalesce(p.nombre, 'Usuario')
    from public.perfiles p
    where p.user_id = auth.uid()
      and lower(p.estado) = 'activo'
    limit 1
$$;

create or replace function public.kilvio_current_caja_turno_id()
returns bigint
language sql
stable
security invoker
set search_path = public
as $$
    select c.id
    from public.cajas_turno c
    where c.usuario_id = auth.uid()
      and c.estado = 'abierta'
    order by c.created_at desc
    limit 1
$$;

create or replace function public.set_caja_turno_id()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
    if new.caja_turno_id is null then
        new.caja_turno_id := public.kilvio_current_caja_turno_id();
    end if;

    return new;
end;
$$;

