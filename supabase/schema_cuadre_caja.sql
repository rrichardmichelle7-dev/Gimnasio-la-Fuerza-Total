create or replace function public.abrir_caja_turno(
    p_monto_inicial numeric default 0,
    p_observaciones text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    v_auth_uid uuid := auth.uid();
    v_perfil record;
    v_caja_id bigint;
begin
    if v_auth_uid is null then
        raise exception 'Usuario no autenticado';
    end if;

    select *
    into v_perfil
    from public.kilvio_current_user_profile()
    limit 1;

    if v_perfil.gimnasio_id is null then
        raise exception 'Perfil activo no valido';
    end if;

    if v_perfil.rol not in ('administrador', 'recepcion') then
        raise exception 'Sin permiso para abrir caja';
    end if;

    if coalesce(p_monto_inicial, 0) < 0 then
        raise exception 'El monto inicial no puede ser negativo';
    end if;

    if exists (
        select 1
        from public.cajas_turno c
        where c.usuario_id = v_auth_uid
          and c.estado = 'abierta'
    ) then
        raise exception 'Este usuario ya tiene una caja abierta';
    end if;

    insert into public.cajas_turno (
        gimnasio_id,
        usuario_id,
        usuario_nombre,
        fecha,
        hora_apertura,
        monto_inicial,
        estado,
        observaciones
    )
    values (
        v_perfil.gimnasio_id,
        v_auth_uid,
        v_perfil.nombre,
        current_date,
        localtime,
        coalesce(p_monto_inicial, 0),
        'abierta',
        p_observaciones
    )
    returning id into v_caja_id;

    return jsonb_build_object(
        'caja_id', v_caja_id,
        'estado', 'abierta',
        'mensaje', 'Caja abierta correctamente'
    );
end;
$$;

create or replace function public.cerrar_caja_turno(
    p_caja_id bigint,
    p_monto_entregado numeric,
    p_observaciones text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    v_auth_uid uuid := auth.uid();
    v_perfil record;
    v_caja public.cajas_turno%rowtype;
    v_mensualidades numeric(12,2) := 0;
    v_ventas_pos numeric(12,2) := 0;
    v_ingresos_diarios numeric(12,2) := 0;
    v_efectivo numeric(12,2) := 0;
    v_tarjeta numeric(12,2) := 0;
    v_total numeric(12,2) := 0;
    v_diferencia numeric(12,2) := 0;
begin
    if v_auth_uid is null then
        raise exception 'Usuario no autenticado';
    end if;

    if p_monto_entregado is null or p_monto_entregado < 0 then
        raise exception 'El monto entregado debe ser mayor o igual a cero';
    end if;

    select *
    into v_perfil
    from public.kilvio_current_user_profile()
    limit 1;

    if v_perfil.gimnasio_id is null then
        raise exception 'Perfil activo no valido';
    end if;

    if v_perfil.rol not in ('administrador', 'recepcion') then
        raise exception 'Sin permiso para cerrar caja';
    end if;

    select *
    into v_caja
    from public.cajas_turno c
    where c.id = p_caja_id
      and c.gimnasio_id = v_perfil.gimnasio_id
    for update;

    if not found then
        raise exception 'Caja no encontrada';
    end if;

    if v_caja.estado <> 'abierta' then
        raise exception 'La caja ya esta cerrada';
    end if;

    if v_caja.usuario_id <> v_auth_uid and v_perfil.rol <> 'administrador' then
        raise exception 'Solo puedes cerrar tu propia caja';
    end if;

    select coalesce(sum(monto), 0)
    into v_mensualidades
    from public.pagos
    where caja_turno_id = p_caja_id
      and lower(coalesce(estado, '')) = 'pagado';

    select coalesce(sum(total), 0)
    into v_ventas_pos
    from public.ventas
    where caja_turno_id = p_caja_id
      and lower(coalesce(estado, 'confirmada')) <> 'anulada';

    select coalesce(sum(total), 0)
    into v_ingresos_diarios
    from public.ingresos_diarios
    where caja_turno_id = p_caja_id;

    select coalesce(sum(monto), 0)
    into v_efectivo
    from public.pagos
    where caja_turno_id = p_caja_id
      and lower(coalesce(estado, '')) = 'pagado'
      and lower(coalesce(metodo_pago, '')) = 'efectivo';

    select v_efectivo + coalesce(sum(total), 0)
    into v_efectivo
    from public.ventas
    where caja_turno_id = p_caja_id
      and lower(coalesce(estado, 'confirmada')) <> 'anulada'
      and lower(coalesce(metodo_pago, '')) = 'efectivo';

    v_efectivo := v_efectivo + v_ingresos_diarios;

    select coalesce(sum(monto), 0)
    into v_tarjeta
    from public.pagos
    where caja_turno_id = p_caja_id
      and lower(coalesce(estado, '')) = 'pagado'
      and lower(coalesce(metodo_pago, '')) in ('tarjeta', 'transferencia');

    select v_tarjeta + coalesce(sum(total), 0)
    into v_tarjeta
    from public.ventas
    where caja_turno_id = p_caja_id
      and lower(coalesce(estado, 'confirmada')) <> 'anulada'
      and lower(coalesce(metodo_pago, '')) = 'tarjeta';

    v_total := v_mensualidades + v_ventas_pos + v_ingresos_diarios;
    v_diferencia := p_monto_entregado - (v_caja.monto_inicial + v_efectivo);

    update public.cajas_turno
    set
        hora_cierre = localtime,
        total_efectivo = v_efectivo,
        total_tarjeta = v_tarjeta,
        total_generado = v_total,
        monto_entregado = p_monto_entregado,
        diferencia = v_diferencia,
        estado = 'cerrada',
        observaciones = nullif(trim(concat_ws(E'\n', v_caja.observaciones, p_observaciones)), '')
    where id = p_caja_id;

    return jsonb_build_object(
        'caja_id', p_caja_id,
        'estado', 'cerrada',
        'total_efectivo', v_efectivo,
        'total_tarjeta', v_tarjeta,
        'total_generado', v_total,
        'monto_entregado', p_monto_entregado,
        'diferencia', v_diferencia,
        'resultado', case
            when v_diferencia = 0 then 'Cuadre correcto'
            when v_diferencia > 0 then 'Sobrante'
            else 'Faltante'
        end,
        'mensaje', 'Caja cerrada correctamente'
    );
end;
$$;

