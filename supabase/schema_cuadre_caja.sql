with check (
    exists (
        select 1
        from public.perfiles p
        where p.user_id = auth.uid()
          and lower(p.estado) = 'activo'
          and p.gimnasio_id = cajas_turno.gimnasio_id
          and lower(p.rol) in ('administrador', 'recepcion')
          and (lower(p.rol) = 'administrador' or cajas_turno.usuario_id = auth.uid())
    )
);

